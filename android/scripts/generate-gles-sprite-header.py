#!/usr/bin/env python3
"""Generate a GLES 3.00 shader header from TaktChase's desktop sprite shaders.

The desktop sources remain the source of truth. Only the version directive and
the fragment shader's required default float precision are adapted here.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


def load_shader(path: Path, *, fragment: bool) -> str:
    source = path.read_text(encoding="utf-8")
    lines = source.splitlines()
    if not lines or lines[0].strip() != "#version 330":
        raise SystemExit(
            f"{path}: expected '#version 330' on the first line; "
            "review shader changes before adapting them for GLES"
        )

    lines[0] = "#version 300 es"
    if fragment:
        # GLSL ES requires a default float precision in fragment shaders.
        lines.insert(1, "precision mediump float;")

    return "\n".join(lines) + ("\n" if source.endswith("\n") else "")


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {Path(sys.argv[0]).name} OUTPUT_HEADER", file=sys.stderr)
        return 2

    repo = Path(__file__).resolve().parents[2]
    assets = repo / "assets" / "shaders"
    vertex = load_shader(assets / "sprite.vsh", fragment=False)
    fragment = load_shader(assets / "sprite.fsh", fragment=True)
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)

    header = (
        "/* Generated from assets/shaders/sprite.vsh and sprite.fsh. "
        "Do not edit this file directly. */\n"
        "#ifndef TAKTCHASE_SPRITE_GLES_H\n"
        "#define TAKTCHASE_SPRITE_GLES_H\n\n"
        f"static const char *kSpriteVertexGlesSrc = {json.dumps(vertex)};\n"
        f"static const char *kSpriteFragmentGlesSrc = {json.dumps(fragment)};\n\n"
        "#endif\n"
    )
    output.write_text(header, encoding="utf-8")
    print("Generated GLES 3.00 variants from the game's desktop sprite shaders.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
